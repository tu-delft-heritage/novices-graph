export function formatters(language = "en") {
  const locale = language === "nl" ? "nl-NL" : "en-US";
  const integer = new Intl.NumberFormat(locale, {maximumFractionDigits: 0});
  const share = new Intl.NumberFormat(locale, {style: "percent", minimumFractionDigits: 1, maximumFractionDigits: 1});
  const axis = new Intl.NumberFormat(locale, {style: "percent", maximumFractionDigits: 0});
  return {
    number: (value) => integer.format(value),
    percent: (value) => value == null ? translate(language, "Not defined") : share.format(value),
    axisPercent: (value) => axis.format(value)
  };
}
